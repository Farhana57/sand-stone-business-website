import { describe, expect, it } from 'vitest'
import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import LanguageProvider from '../../i18n/LanguageProvider.jsx'
import { isOrderApiConfigured } from '../../lib/api.js'
import OrderForm from './OrderForm.jsx'

/**
 * Integration test against a real running API (Express + MongoDB).
 *
 * It is skipped unless VITE_API_URL is set, so `npm test` stays fast and
 * offline-friendly. To run it:
 *
 *   npm run dev:memory --prefix server          # or your own MongoDB
 *   VITE_API_URL=http://127.0.0.1:5000 npx vitest run src/components/order/OrderForm.integration.test.jsx
 */
describe.skipIf(!isOrderApiConfigured)('OrderForm against the live order API', () => {
  it('saves the order on the server and shows the returned reference', async () => {
    const user = userEvent.setup()

    render(
      <LanguageProvider initialLanguage="en">
        <OrderForm />
      </LanguageProvider>,
    )

    await user.type(screen.getByLabelText(/Name/), 'Integration Buyer')
    await user.type(screen.getByLabelText(/Mobile number/), '01712345678')
    await user.selectOptions(screen.getByLabelText(/Which material\?/), 'sylhet-sand')
    await user.type(screen.getByLabelText(/Quantity/), '150')
    await user.type(screen.getByLabelText(/Delivery address/), 'House 12, Road 4, West Rampura, Dhaka')

    await user.click(screen.getByRole('button', { name: 'Send order request' }))

    // The reference is generated by the server, so seeing it proves the round trip.
    expect(await screen.findByText(/Order reference SS-\d{8}-\d{4}/)).toBeInTheDocument()
    expect(screen.getByText('Your request has been sent')).toBeInTheDocument()
    expect(screen.queryByText(/ready in WhatsApp/)).not.toBeInTheDocument()
  })

  it('shows an honest error when the server rejects the order', async () => {
    const user = userEvent.setup()

    render(
      <LanguageProvider initialLanguage="en">
        <OrderForm />
      </LanguageProvider>,
    )

    await user.type(screen.getByLabelText(/Name/), 'Integration Buyer')
    await user.type(screen.getByLabelText(/Mobile number/), '01712345678')
    await user.selectOptions(screen.getByLabelText(/Which material\?/), 'sylhet-sand')
    await user.type(screen.getByLabelText(/Quantity/), '9999999')
    await user.type(screen.getByLabelText(/Delivery address/), 'House 12, Road 4, West Rampura, Dhaka')

    await user.click(screen.getByRole('button', { name: 'Send order request' }))

    expect(await screen.findByText('Sorry, that did not go through')).toBeInTheDocument()
    expect(screen.queryByText(/Order reference/)).not.toBeInTheDocument()
  })
})
